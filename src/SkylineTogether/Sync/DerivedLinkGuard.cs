    /// <summary>
    /// Keeps the derived net links (<see cref="DerivedNetLink"/>, ARCHITECTURE.md#derived-net-links) free of references
    /// to destroyed entities, on the host and on clients. Streets and road connections here; the node and edge lists
    /// (<c>ConnectedEdge</c>, <c>ConnectedNode</c>, <c>Edge</c>) in <c>DerivedLinkGuard.Nodes.cs</c>. One direction of each pair travels on the wire (an aggregate's
    /// edge list, a building's road edge) and the other is derived by each peer's game (an edge's <c>Aggregated</c>, an
    /// edge's <c>ConnectedBuilding</c> list): <c>Aggregated</c> and <c>ConnectedBuilding</c> are presence-only in saves and
    /// records, the game rebuilds them on load and keeps both directions in step as it edits. A peer whose two directions
    /// come from different sources keeps stale entries: deleting the edge or building then cleans the direction the game
    /// knows of, and the other one keeps naming a destroyed entity. <c>AggregateSystem</c>, <c>AggregateMeshSystem</c> and
    /// <c>RoadConnectionSystem</c> index such references without a check when a road next to them is built or connected:
    /// the native crash of the client building connected roads.
    /// <list type="bullet">
    /// <item><b>After every apply</b> (<see cref="AfterApply"/>): an aggregate whose list a record wrote takes its listed
    /// edges (they leave the list of the aggregate they named; an emptied local street is deleted), as the game's own
    /// <c>AggregatedSystem</c> does on load; a building whose record was written is listed by its road edge.</item>
    /// <item><b>End of the Modification phases</b> (<see cref="EndOfModification"/>): once per session a full pass, then in
    /// every frame that deletes edges, aggregates or buildings, every pointer or list entry still naming one is cleared
    /// (the game already moved the ones it knows of; what is left would name a destroyed entity next frame).</item>
    /// <item><b>Right before the game reads them</b> (<see cref="BeforeAggregates"/>, <see cref="BeforeRoadConnections"/>,
    /// <see cref="BeforeAggregateMeshes"/>): the references of the entities the system is about to process are checked once
    /// more (destroyed or wrong kind: cleared).</item>
    /// </list>
    /// It never writes a tool preview (<c>Temp</c>, regenerated by the tool, and handled safely by the game's code), never
    /// creates an entity, and only clears or moves references; every repair is a forensics line. Main thread only.
    /// </summary>
    internal sealed partial class DerivedLinkGuard
    {
        private readonly long[] _repairs = new long[DerivedNetLinkRules.Count];
        private readonly DerivedLinkDeletions<Entity> _deleted = new DerivedLinkDeletions<Entity>();
        private readonly List<Entity> _scratch = new List<Entity>();
        private readonly List<Entity> _hits = new List<Entity>();
        private readonly HashSet<Entity> _edges = new HashSet<Entity>();
        private readonly HashSet<Entity> _aggregates = new HashSet<Entity>();
        private readonly List<MembershipOp<Entity>> _ops = new List<MembershipOp<Entity>>();
        private World _world;
        private EntityQuery _deletedEdges, _deletedAggregates, _deletedBuildings;
        private EntityQuery _allAggregates, _allAggregated, _allBuildings, _allConnected;
        private EntityQuery _modifiedAggregated, _modifiedConnected, _modifiedBuildings, _taggedAggregates;
        private readonly Func<Entity, bool> _isDeletedEdge, _isKeptEdge, _isGoneAggregate, _isDeletedBuilding, _isKeptBuilding;
        private bool _fullPassDone;
        private long _fullPasses, _deletionPasses, _moved, _listed, _emptiedDeleted;

        /// <summary>The ids of the session (an unbound street is local and may be deleted when emptied); set by the controller.</summary>
        public NetIdSystem Ids;

        public DerivedLinkGuard()
        {
            _isDeletedEdge = e => _deleted.IsDeletedEdge(e);
            _isKeptEdge = e => !_deleted.IsDeletedEdge(e);
            _isGoneAggregate = a => _deleted.IsGoneAggregate(a);
            _isDeletedBuilding = b => _deleted.IsDeletedBuilding(b);
            _isKeptBuilding = b => !_deleted.IsDeletedBuilding(b);
        }

        public long Repairs
        {
            get
            {
                long n = 0;
                foreach (long r in _repairs) n += r;
                return n;
            }
        }

        public string Describe()
        {
            var parts = new List<string>();
            for (int i = 0; i < _repairs.Length; i++)
            {
                if (_repairs[i] > 0) parts.Add(DerivedNetLinkRules.Name((DerivedNetLink)i) + " " + _repairs[i]);
            }
            return "derived net links: " + _fullPasses + " full pass(es), " + _deletionPasses + " deletion passes, " + Repairs + " references to destroyed entities cleared"
                   + (parts.Count > 0 ? " (" + string.Join(", ", parts) + ")" : "") + "; " + _moved + " edges moved to the street a record lists them in, "
                   + _emptiedDeleted + " emptied local streets deleted, " + _listed + " buildings listed by their road edge; " + DescribeNodes();
        }

        public void Reset()
        {
            Array.Clear(_repairs, 0, _repairs.Length);
            _deleted.Clear();
            _fullPassDone = false;
            _fullPasses = _deletionPasses = _moved = _listed = _emptiedDeleted = 0;
            ResetNodes();
            _world = null;
        }

        private void Ensure(EntityManager em)
        {
            if (_world == em.World && _world != null) return;
            _world = em.World;
            _fullPassDone = false;
            ComponentType temp = ComponentType.ReadOnly<Game.Tools.Temp>();
            ComponentType deleted = ComponentType.ReadOnly<Deleted>();
            EntityQuery Q(ComponentType[] all, ComponentType[] any, ComponentType[] none) =>
                em.CreateEntityQuery(new EntityQueryDesc { All = all, Any = any ?? Array.Empty<ComponentType>(), None = none ?? Array.Empty<ComponentType>() });
            _deletedEdges = Q(new[] { ComponentType.ReadOnly<Edge>(), deleted }, null, new[] { temp });
            _deletedAggregates = Q(new[] { ComponentType.ReadOnly<Aggregate>(), deleted }, null, new[] { temp });
            _deletedBuildings = Q(new[] { ComponentType.ReadOnly<Building>(), deleted }, null, new[] { temp });
            _allAggregates = Q(new[] { ComponentType.ReadOnly<Aggregate>(), ComponentType.ReadOnly<AggregateElement>() }, null, new[] { temp, deleted });
            _allAggregated = Q(new[] { ComponentType.ReadOnly<Aggregated>() }, null, new[] { temp, deleted });
            _allBuildings = Q(new[] { ComponentType.ReadOnly<Building>() }, null, new[] { temp, deleted });
            _allConnected = Q(new[] { ComponentType.ReadOnly<ConnectedBuilding>() }, null, new[] { temp, deleted });
            ComponentType[] changed = { ComponentType.ReadOnly<Created>(), ComponentType.ReadOnly<Updated>(), deleted };
            _modifiedAggregated = Q(new[] { ComponentType.ReadOnly<Aggregated>() }, changed, new[] { temp });
            _modifiedConnected = Q(new[] { ComponentType.ReadOnly<Edge>(), ComponentType.ReadOnly<ConnectedBuilding>() }, new[] { ComponentType.ReadOnly<Updated>(), deleted }, new[] { temp });
            _modifiedBuildings = Q(new[] { ComponentType.ReadOnly<Building>() }, new[] { ComponentType.ReadOnly<Updated>(), deleted }, new[] { temp });
            _taggedAggregates = Q(new[] { ComponentType.ReadOnly<Aggregate>(), ComponentType.ReadOnly<AggregateElement>() },
                new[] { ComponentType.ReadOnly<Created>(), ComponentType.ReadOnly<Updated>(), ComponentType.ReadOnly<BatchesUpdated>(), deleted }, new[] { temp });
            EnsureNodes(em);
        }

        // ================================================================== usable targets

        private static bool IsTemp(EntityManager em, Entity e) => em.HasComponent<Game.Tools.Temp>(e);

        /// <summary>An aggregate a pointer may name: it exists and has its edge list (the game indexes the list and its prefab).</summary>
        private static bool UsableAggregate(EntityManager em, Entity a) => em.Exists(a) && em.HasBuffer<AggregateElement>(a) && em.HasComponent<Game.Prefabs.PrefabRef>(a);

        /// <summary>An element an aggregate list may hold: an edge with its pointer and prefab (<c>ValidateAggregate</c> reads both).</summary>
        private static bool UsableElement(EntityManager em, Entity e) => em.Exists(e) && em.HasComponent<Edge>(e) && em.HasComponent<Aggregated>(e) && em.HasComponent<Game.Prefabs.PrefabRef>(e);

        /// <summary>A road edge a building may name: its geometry and list exist (<c>RoadConnectionSystem</c> indexes them).</summary>
        private static bool UsableRoadEdge(EntityManager em, Entity e) =>
            em.Exists(e) && em.HasBuffer<ConnectedBuilding>(e) && em.HasComponent<EdgeGeometry>(e) && em.HasComponent<StartNodeGeometry>(e) && em.HasComponent<EndNodeGeometry>(e);

        /// <summary>A building an edge's list may name (<c>RoadConnectionSystem</c> reads its building, prefab and transform).</summary>
        private static bool UsableListedBuilding(EntityManager em, Entity b) =>
            em.Exists(b) && em.HasComponent<Building>(b) && em.HasComponent<Game.Prefabs.PrefabRef>(b) && em.HasComponent<Game.Objects.Transform>(b);

        // ================================================================== repairs

        private void ClearPointer(EntityManager em, Entity edge, string why)
        {
            Aggregated a = em.GetComponentData<Aggregated>(edge);
            Entity old = a.m_Aggregate;
            a.m_Aggregate = Entity.Null;
            em.SetComponentData(edge, a);
            _repairs[(int)DerivedNetLink.AggregatePointer]++;
            Forensics.Cleanup("derived links", em, edge, DerivedNetLinkRules.Name(DerivedNetLink.AggregatePointer) + " named " + Forensics.Describe(em, old) + " (" + why + ") -> cleared");
        }

        private void ClearRoadEdge(EntityManager em, Entity building, string why)
        {
            Building b = em.GetComponentData<Building>(building);
            Entity old = b.m_RoadEdge;
            b.m_RoadEdge = Entity.Null;
            b.m_CurvePosition = 0;
            em.SetComponentData(building, b);
            _repairs[(int)DerivedNetLink.RoadEdge]++;
            Forensics.Cleanup("derived links", em, building, DerivedNetLinkRules.Name(DerivedNetLink.RoadEdge) + " named " + Forensics.Describe(em, old) + " (" + why + ") -> cleared");
        }

        /// <summary>Removes the elements of an aggregate's list that <paramref name="keep"/> rejects; returns the number removed.</summary>
        private int PruneAggregate(EntityManager em, Entity aggregate, Func<Entity, bool> keep, string why)
        {
            DynamicBuffer<AggregateElement> ro = em.GetBuffer<AggregateElement>(aggregate, true);
            bool any = false;
            for (int i = 0; i < ro.Length && !any; i++) any = !keep(ro[i].m_Edge);
            if (!any) return 0;
            _scratch.Clear();
            for (int i = 0; i < ro.Length; i++) _scratch.Add(ro[i].m_Edge);
            Entity first = Entity.Null;
            foreach (Entity e in _scratch)
            {
                if (keep(e)) continue;
                first = e;
                break;
            }
            int removed = DerivedNetLinkRules.Prune(_scratch, keep);
            DynamicBuffer<AggregateElement> rw = em.GetBuffer<AggregateElement>(aggregate);
            rw.Clear();
            foreach (Entity e in _scratch) rw.Add(new AggregateElement(e));
            _repairs[(int)DerivedNetLink.AggregateElement] += removed;
            Forensics.Cleanup("derived links", em, aggregate, DerivedNetLinkRules.Name(DerivedNetLink.AggregateElement) + ": " + removed + " element(s) dropped, e.g. "
                                                               + Forensics.Describe(em, first) + " (" + why + ")" + (_scratch.Count == 0 ? "; the list is empty now" : ""));
            _scratch.Clear();
            return removed;
        }

        /// <summary>Removes the entries of an edge's building list that <paramref name="keep"/> rejects; returns the number removed.</summary>
        private int PruneConnected(EntityManager em, Entity edge, Func<Entity, bool> keep, string why)
        {
            DynamicBuffer<ConnectedBuilding> ro = em.GetBuffer<ConnectedBuilding>(edge, true);
            bool any = false;
            for (int i = 0; i < ro.Length && !any; i++) any = !keep(ro[i].m_Building);
            if (!any) return 0;
            _scratch.Clear();
            for (int i = 0; i < ro.Length; i++) _scratch.Add(ro[i].m_Building);
            Entity first = Entity.Null;
            foreach (Entity b in _scratch)
            {
                if (keep(b)) continue;
                first = b;
                break;
            }
            int removed = DerivedNetLinkRules.Prune(_scratch, keep);
            DynamicBuffer<ConnectedBuilding> rw = em.GetBuffer<ConnectedBuilding>(edge);
            rw.Clear();
            foreach (Entity b in _scratch) rw.Add(new ConnectedBuilding(b));
            _repairs[(int)DerivedNetLink.ConnectedBuilding] += removed;
            Forensics.Cleanup("derived links", em, edge, DerivedNetLinkRules.Name(DerivedNetLink.ConnectedBuilding) + ": " + removed + " entr(ies) dropped, e.g. "
                                                          + Forensics.Describe(em, first) + " (" + why + ")");
            _scratch.Clear();
            return removed;
        }

        /// <summary>
        /// The holders of <paramref name="query"/> whose list (<typeparamref name="T"/>) has an element that
        /// <paramref name="reject"/> rejects (a chunk walk, read-only: only the hits are written afterwards).
        /// </summary>
        private static void FindLists<T>(EntityManager em, EntityQuery query, Func<T, Entity> get, Func<Entity, bool> reject, List<Entity> into)
            where T : unmanaged, IBufferElementData
        {
            into.Clear();
            if (query.IsEmptyIgnoreFilter) return;
            query.CompleteDependency();
            BufferTypeHandle<T> handle = em.GetBufferTypeHandle<T>(true);
            EntityTypeHandle entityType = em.GetEntityTypeHandle();
            NativeArray<ArchetypeChunk> chunks = query.ToArchetypeChunkArray(Allocator.Temp);
            try
            {
                foreach (ArchetypeChunk chunk in chunks)
                {
                    BufferAccessor<T> lists = chunk.GetBufferAccessor(ref handle);
                    NativeArray<Entity> holders = chunk.GetNativeArray(entityType);
                    for (int i = 0; i < lists.Length; i++)
                    {
                        DynamicBuffer<T> list = lists[i];
                        for (int k = 0; k < list.Length; k++)
                        {
                            if (!reject(get(list[k]))) continue;
                            into.Add(holders[i]);
                            break;
                        }
                    }
                }
            }
            finally
            {
                chunks.Dispose();
            }
        }

        /// <summary>The holders of <paramref name="query"/> whose non-null pointer (<typeparamref name="T"/>) <paramref name="reject"/> rejects.</summary>
        private static void FindPointers<T>(EntityManager em, EntityQuery query, Func<T, Entity> get, Func<Entity, bool> reject, List<Entity> into)
            where T : unmanaged, IComponentData
        {
            into.Clear();
            if (query.IsEmptyIgnoreFilter) return;
            query.CompleteDependency();
            ComponentTypeHandle<T> handle = em.GetComponentTypeHandle<T>(true);
            EntityTypeHandle entityType = em.GetEntityTypeHandle();
            NativeArray<ArchetypeChunk> chunks = query.ToArchetypeChunkArray(Allocator.Temp);
            try
            {
                foreach (ArchetypeChunk chunk in chunks)
                {
                    NativeArray<T> values = chunk.GetNativeArray(ref handle);
                    NativeArray<Entity> holders = chunk.GetNativeArray(entityType);
                    for (int i = 0; i < values.Length; i++)
                    {
                        Entity target = get(values[i]);
                        if (target != Entity.Null && reject(target)) into.Add(holders[i]);
                    }
                }
            }
            finally
            {
                chunks.Dispose();
            }
        }

        private static readonly Func<AggregateElement, Entity> ElementOf = x => x.m_Edge;
        private static readonly Func<ConnectedBuilding, Entity> ListedOf = x => x.m_Building;
        private static readonly Func<Aggregated, Entity> PointerOf = x => x.m_Aggregate;
        private static readonly Func<Building, Entity> RoadOf = x => x.m_RoadEdge;

        /// <summary>The entities of a query (chunk walk after completing its jobs).</summary>
        private static void Collect(EntityQuery query, List<Entity> into)
        {
            into.Clear();
            if (query.IsEmptyIgnoreFilter) return;
            query.CompleteDependency();
            NativeArray<Entity> entities = query.ToEntityArray(Allocator.Temp);
            try
            {
                foreach (Entity e in entities) into.Add(e);
            }
            finally
            {
                entities.Dispose();
            }
        }

        // ================================================================== after an apply

        /// <summary>
        /// Right after a batch or proposal was applied (frame start, before every game system): the street membership the
        /// written aggregate lists say, and the written buildings listed by their road edge. <paramref name="touched"/> are
        /// the entities the apply wrote, tagged or cascaded.
        /// </summary>
        public void AfterApply(EntityManager em, IEnumerable<Entity> touched)
        {
            if (touched == null) return;
            Ensure(em);
            int moved = 0, emptied = 0, listed = 0;
            foreach (Entity t in touched)
            {
                if (t == Entity.Null || !em.Exists(t) || em.HasComponent<Deleted>(t) || IsTemp(em, t)) continue;
                if (em.HasComponent<Aggregate>(t) && em.HasBuffer<AggregateElement>(t))
                {
                    PruneAggregate(em, t, e => UsableElement(em, e), "not an edge here");
                    moved += TakeListedEdges(em, t, ref emptied);
                }
                if (em.HasComponent<Building>(t))
                {
                    Entity road = em.GetComponentData<Building>(t).m_RoadEdge;
                    if (road == Entity.Null) continue;
                    if (!UsableRoadEdge(em, road))
                    {
                        ClearRoadEdge(em, t, "not a road edge here");
                        continue;
                    }
                    DynamicBuffer<ConnectedBuilding> list = em.GetBuffer<ConnectedBuilding>(road, true);
                    bool found = false;
                    for (int i = 0; i < list.Length && !found; i++) found = list[i].m_Building == t;
                    if (found) continue;
                    em.GetBuffer<ConnectedBuilding>(road).Add(new ConnectedBuilding(t));
                    listed++;
                }
            }
            _moved += moved;
            _listed += listed;
            _emptiedDeleted += emptied;
            if (moved + emptied > 0)
            {
                Forensics.Write("cleanup: derived links: street membership from the applied lists: " + moved + " edge(s) moved to the street that lists them"
                                + (emptied > 0 ? ", " + emptied + " emptied local street(s) deleted" : ""));
            }
        }

        /// <summary>Every listed edge names <paramref name="aggregate"/> and leaves the list of the street it named before.</summary>
        private int TakeListedEdges(EntityManager em, Entity aggregate, ref int emptied)
        {
            _scratch.Clear();
            DynamicBuffer<AggregateElement> list = em.GetBuffer<AggregateElement>(aggregate, true);
            for (int i = 0; i < list.Length; i++) _scratch.Add(list[i].m_Edge);
            _ops.Clear();
            AggregateMembership.Plan(aggregate, _scratch, e => em.GetComponentData<Aggregated>(e).m_Aggregate,
                e => em.Exists(e) && em.HasComponent<Aggregated>(e) && !em.HasComponent<Deleted>(e) && !IsTemp(em, e), _ops);
            _scratch.Clear();
            foreach (MembershipOp<Entity> op in _ops)
            {
                em.SetComponentData(op.Edge, new Aggregated { m_Aggregate = op.To });
                Entity from = op.From;
                if (from == Entity.Null || from == op.To || !UsableAggregate(em, from) || IsTemp(em, from)) continue;
                DynamicBuffer<AggregateElement> old = em.GetBuffer<AggregateElement>(from);
                for (int i = old.Length - 1; i >= 0; i--)
                {
                    if (old[i].m_Edge == op.Edge) old.RemoveAt(i);
                }
                // a street of this peer's own (no id: the host does not know it) left without edges goes, as the game deletes it
                if (old.Length == 0 && !em.HasComponent<Deleted>(from) && (Ids == null || Ids.GetNetId(from) == 0))
                {
                    em.AddComponent<Deleted>(from);
                    emptied++;
                }
            }
            int n = _ops.Count;
            _ops.Clear();
            return n;
        }

        // ================================================================== end of the Modification phases

        /// <summary>
        /// ModificationEnd, after its barrier: the first time in a session a full pass over every derived link, then the
        /// deletions of this frame (see the class remarks).
        /// </summary>
        public void EndOfModification(EntityManager em)
        {
            Ensure(em);
            if (!_fullPassDone)
            {
                _fullPassDone = true;
                FullPass(em);
            }
            _deleted.Clear();
            bool edges = !_deletedEdges.IsEmptyIgnoreFilter, aggregates = !_deletedAggregates.IsEmptyIgnoreFilter, buildings = !_deletedBuildings.IsEmptyIgnoreFilter;
            bool nodes = !_deletedNodes.IsEmptyIgnoreFilter;
            if (!edges && !aggregates && !buildings && !nodes) return;
            if (edges)
            {
                Collect(_deletedEdges, _hits);
                foreach (Entity e in _hits) _deleted.Edges.Add(e);
            }
            if (aggregates)
            {
                Collect(_deletedAggregates, _hits);
                foreach (Entity e in _hits) _deleted.Aggregates.Add(e);
            }
            if (buildings)
            {
                Collect(_deletedBuildings, _hits);
                foreach (Entity e in _hits) _deleted.Buildings.Add(e);
            }
            if (nodes)
            {
                Collect(_deletedNodes, _hits);
                foreach (Entity e in _hits) _deleted.Nodes.Add(e);
            }
            _hits.Clear();
            if (!_deleted.HasWork) return;
            _deletionPasses++;
            if (_deleted.Edges.Count > 0)
            {
                // streets that still list a deleted edge (the game rebuilt the list of the street the edge named)
                FindLists(em, _allAggregates, ElementOf, _isDeletedEdge, _hits);
                foreach (Entity a in _hits)
                {
                    if (PruneAggregate(em, a, _isKeptEdge, "deleted this frame") > 0 && em.GetBuffer<AggregateElement>(a, true).Length == 0) _deleted.Emptied.Add(a);
                }
                // buildings whose road edge goes (the game moved the buildings the edge listed)
                FindPointers(em, _allBuildings, RoadOf, _isDeletedEdge, _hits);
                foreach (Entity b in _hits) ClearRoadEdge(em, b, "deleted this frame");
            }
            if (_deleted.Aggregates.Count + _deleted.Emptied.Count > 0)
            {
                // edges that still name a deleted or emptied street (the game re-points the edges of a street it merges)
                FindPointers(em, _allAggregated, PointerOf, _isGoneAggregate, _hits);
                foreach (Entity e in _hits)
                {
                    Entity a = em.GetComponentData<Aggregated>(e).m_Aggregate;
                    ClearPointer(em, e, _deleted.Aggregates.Contains(a) ? "deleted this frame" : "its list is empty");
                }
            }
            if (_deleted.Buildings.Count > 0)
            {
                // edges that still list a deleted building (the game removes it from its road edge's list)
                FindLists(em, _allConnected, ListedOf, _isDeletedBuilding, _hits);
                foreach (Entity e in _hits) PruneConnected(em, e, _isKeptBuilding, "deleted this frame");
            }
            // node lists that still name a deleted edge, edges left at a deleted node
            DeletedNodesAndEdges(em);
            _hits.Clear();
            _deleted.Clear();
        }

        /// <summary>Every derived link checked once (session start): what names a destroyed entity or the wrong kind is cleared.</summary>
        private void FullPass(EntityManager em)
        {
            _fullPasses++;
            long before = Repairs;
            _deleted.Clear();
            FindLists(em, _allAggregates, ElementOf, e => !UsableElement(em, e), _hits);
            foreach (Entity a in _hits) PruneAggregate(em, a, e => UsableElement(em, e), "destroyed or not an edge");
            FindLists(em, _allAggregates, ElementOf, e => true, _hits); // every street with at least one element
            _aggregates.Clear();
            foreach (Entity a in _hits) _aggregates.Add(a);
            Collect(_allAggregates, _hits);
            foreach (Entity a in _hits)
            {
                if (!_aggregates.Contains(a)) _deleted.Emptied.Add(a);
            }
            _aggregates.Clear();
            FindPointers(em, _allAggregated, PointerOf, a => !UsableAggregate(em, a) || IsTemp(em, a) || _deleted.Emptied.Contains(a), _hits);
            foreach (Entity e in _hits)
            {
                Entity a = em.GetComponentData<Aggregated>(e).m_Aggregate;
                bool usable = UsableAggregate(em, a) && !IsTemp(em, a);
                if (DerivedNetLinkRules.MustClear(false, usable, _deleted.Emptied.Contains(a))) ClearPointer(em, e, usable ? "its list is empty" : "destroyed or not a street");
            }
            FindPointers(em, _allBuildings, RoadOf, road => !UsableRoadEdge(em, road), _hits);
            foreach (Entity b in _hits) ClearRoadEdge(em, b, "destroyed or not a road edge");
            FindLists(em, _allConnected, ListedOf, b => !UsableListedBuilding(em, b), _hits);
            foreach (Entity e in _hits) PruneConnected(em, e, b => UsableListedBuilding(em, b), "destroyed or not a building");
            FullPassNodes(em);
            _hits.Clear();
            _deleted.Clear();
            long repaired = Repairs - before;
            Mod.Log?.Info(LogCategory.Integrity, "derived net links checked (streets, road connections, node and edge lists): " + repaired + " reference(s) to destroyed entities cleared"
                                                 + (_broken.Count > 0 ? ", " + _broken.Count + " edge(s) whose node is gone deleted next frame" : ""));
        }

        // ================================================================== right before the game reads them

        /// <summary>
        /// Modification2B, right before <c>AggregateSystem</c>: the streets the modified edges and their neighbours name are
        /// usable and list only edges (<c>ValidateAggregate</c>, <c>CombineAggregate</c>, <c>ShouldCombine</c>).
        /// </summary>
        public void BeforeAggregates(EntityManager em)
        {
            Ensure(em);
            if (_modifiedAggregated.IsEmptyIgnoreFilter) return;
            Collect(_modifiedAggregated, _hits);
            _edges.Clear();
            _aggregates.Clear();
            foreach (Entity e in _hits)
            {
                _edges.Add(e);
                if (!em.HasComponent<Edge>(e)) continue;
                Edge edge = em.GetComponentData<Edge>(e);
                AddNeighbours(em, edge.m_Start);
                AddNeighbours(em, edge.m_End);
            }
            _hits.Clear();
            foreach (Entity e in _edges)
            {
                if (!em.Exists(e) || IsTemp(em, e) || !em.HasComponent<Aggregated>(e)) continue;
                Entity a = em.GetComponentData<Aggregated>(e).m_Aggregate;
                if (a == Entity.Null) continue;
                if (!UsableAggregate(em, a)) ClearPointer(em, e, "destroyed or not a street");
                else _aggregates.Add(a);
            }
            foreach (Entity a in _aggregates)
            {
                if (IsTemp(em, a)) continue;
                PruneAggregate(em, a, e => UsableElement(em, e), "destroyed or not an edge");
                if (em.GetBuffer<AggregateElement>(a, true).Length > 0) continue;
                foreach (Entity e in _edges)
                {
                    if (em.Exists(e) && !IsTemp(em, e) && em.HasComponent<Aggregated>(e) && em.GetComponentData<Aggregated>(e).m_Aggregate == a) ClearPointer(em, e, "its list is empty");
                }
            }
            _edges.Clear();
            _aggregates.Clear();
        }

        private void AddNeighbours(EntityManager em, Entity node)
        {
            if (node == Entity.Null || !em.Exists(node) || !em.HasBuffer<ConnectedEdge>(node)) return;
            DynamicBuffer<ConnectedEdge> edges = em.GetBuffer<ConnectedEdge>(node, true);
            for (int i = 0; i < edges.Length; i++)
            {
                Entity e = edges[i].m_Edge;
                if (e != Entity.Null) _edges.Add(e);
            }
        }

        /// <summary>
        /// Modification4B, right before <c>RoadConnectionSystem</c>: the lists of the modified edges name buildings, and the
        /// road edges of the listed and the modified buildings are road edges.
        /// </summary>
        public void BeforeRoadConnections(EntityManager em)
        {
            Ensure(em);
            bool edges = !_modifiedConnected.IsEmptyIgnoreFilter, buildings = !_modifiedBuildings.IsEmptyIgnoreFilter;
            if (!edges && !buildings) return;
            _edges.Clear(); // the buildings to check (reused set)
            if (edges)
            {
                Collect(_modifiedConnected, _hits);
                foreach (Entity e in _hits)
                {
                    if (!em.Exists(e)) continue;
                    PruneConnected(em, e, b => UsableListedBuilding(em, b), "destroyed or not a building");
                    DynamicBuffer<ConnectedBuilding> list = em.GetBuffer<ConnectedBuilding>(e, true);
                    for (int i = 0; i < list.Length; i++) _edges.Add(list[i].m_Building);
                }
            }
            if (buildings)
            {
                Collect(_modifiedBuildings, _hits);
                foreach (Entity b in _hits) _edges.Add(b);
            }
            _hits.Clear();
            foreach (Entity b in _edges)
            {
                if (!em.Exists(b) || IsTemp(em, b) || !em.HasComponent<Building>(b)) continue;
                Entity road = em.GetComponentData<Building>(b).m_RoadEdge;
                if (road != Entity.Null && !UsableRoadEdge(em, road)) ClearRoadEdge(em, b, "destroyed or not a road edge");
            }
            _edges.Clear();
        }

        /// <summary>
        /// PreCulling, right before <c>AggregateMeshSystem</c>: the lists of the streets whose labels it rebuilds name edges,
        /// and the edge lists of their edges' nodes name edges (<c>CompositionChange</c> indexes both entries of a node with
        /// two edges).
        /// </summary>
        public void BeforeAggregateMeshes(EntityManager em)
        {
            Ensure(em);
            if (_taggedAggregates.IsEmptyIgnoreFilter) return;
            Collect(_taggedAggregates, _hits);
            foreach (Entity a in _hits)
            {
                if (!em.Exists(a)) continue;
                PruneAggregate(em, a, e => em.Exists(e) && em.HasComponent<Edge>(e), "destroyed or not an edge");
                if (!IsTemp(em, a)) CheckListedEdgeNodes(em, a);
            }
            _hits.Clear();
        }
    }
